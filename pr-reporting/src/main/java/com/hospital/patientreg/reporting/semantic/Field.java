package com.hospital.patientreg.reporting.semantic;

import com.fasterxml.jackson.annotation.JsonIgnore;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonInclude;
import java.util.List;
import java.util.Map;

/**
 * One field of a dataset. {@code role} is "dimension" (can be shown, filtered, grouped and, if it lists
 * {@code aggregations}, aggregated) or "measure" (a fixed aggregate {@code expression}, e.g. count()).
 * {@code multiHospital} fields (the hospital itself) are offered only to users who see several hospitals.
 * <p>
 * Besides the catalogue's standard fields, the effective catalogue of a user (stage 5b) contains:
 * hospitals' custom form fields (origin "custom"), shared calculated fields ("shared") and the report's own
 * calculated fields ("report"). Their SQL is generated by the application only; {@code params} holds the
 * bound values of text literals in a calculated field's SQL.
 */
@JsonIgnoreProperties(ignoreUnknown = true)
@JsonInclude(JsonInclude.Include.NON_DEFAULT)
public record Field(
        String name,
        String label,
        FieldType type,
        String role,
        List<String> aggregations,
        Integer scale,
        String expression,
        boolean suggest,
        boolean hidden,
        boolean multiHospital,
        String sensitivity,
        String origin,
        String formula,
        String description,
        @JsonIgnore Map<String, Object> params) {

    public Field {
        params = params == null ? Map.of() : Map.copyOf(params);
    }

    public boolean isMeasure() {
        return "measure".equals(role);
    }

    public boolean allowsAggregation(String agg) {
        return aggregations != null && aggregations.contains(agg);
    }

    /** The same field with other SQL, label and visibility (applied per hospital by the effective catalogue). */
    public Field with(String newLabel, String newExpression) {
        return new Field(name, newLabel, type, role, aggregations, scale, newExpression, suggest, hidden, multiHospital,
                sensitivity, origin, formula, description, params);
    }

    /** Built by the application (custom and calculated fields). */
    public static Field generated(String name, String label, FieldType type, String role, List<String> aggregations,
                                  String expression, boolean suggest, String origin, String formula, String description,
                                  Map<String, Object> params) {
        return new Field(name, label, type, role, aggregations, null, expression, suggest, false, false, null, origin,
                formula, description, params);
    }
}
